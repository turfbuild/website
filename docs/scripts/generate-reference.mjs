async function main() {
  VERSION = serverVersion();
  console.log(`turf-mcp-server ${VERSION} (${BIN})`);

  const byTier = {};
  for (const tier of TIERS) {
    byTier[tier] = await readTier(tier);
    const t = byTier[tier];
    console.log(
      `  ${tier.padEnd(5)} tools ${t.tools.length}, prompts ${t.prompts.length}, resources ${t.resources.length}, templates ${t.templates.length}`,
    );
  }

  // Every tool, prompt and resource any tier lists, with the tiers that list it. A definition that
  // differs between tiers is reported; the full tier's (else the first tier's) is the one written.
  const collect = (key, id) => {
    const items = new Map();
    const tiers = {};
    for (const tier of TIERS) {
      for (const item of byTier[tier][key]) {
        const k = id(item);
        (tiers[k] ||= []).push(tier);
        const prev = items.get(k);
        if (prev && JSON.stringify(prev) !== JSON.stringify(item)) console.warn(`  warning: ${key} ${k} differs at the ${tier} tier`);
        if (!prev || tier === 'full') items.set(k, item);
      }
    }
    return { items: [...items.keys()].sort().map((k) => items.get(k)), tiers };
  };
  const tools = collect('tools', (t) => t.name);
  const prompts = collect('prompts', (p) => p.name);
  const resources = collect('resources', (r) => r.uri);
  const templates = collect('templates', (r) => r.uriTemplate);

  // The generated directories are wholly generated: clear them so a tool or file the server dropped
  // leaves no stale page behind.
  for (const dir of ['tools', 'skills']) fs.rmSync(path.join(REF, dir), { recursive: true, force: true });

  const names = tools.items.map((t) => t.name);
  for (const tool of tools.items) write(`tools/${tool.name}.md`, toolPage(tool, tools.tiers[tool.name], names));
  write('prompts.md', promptsPage(prompts.items, prompts.tiers));
  write('resources.md', resourcesPage(resources.items, templates.items, { ...resources.tiers, ...templates.tiers }));
  skillPages(byTier.full.skills);
  write('instructions.md', instructionsPage(byTier, knownIn(byTier.full.skills)));

  const files = Object.values(byTier.full.skills).reduce((n, s) => n + Object.keys(s.files).length, 0);
  console.log(
    `wrote ${written.length} pages: ${tools.items.length} tools, ${prompts.items.length} prompts, ` +
      `${resources.items.length + templates.items.length} resources, ${SKILLS.length} skills + ${files} reference files, instructions`,
  );
}

main().catch((e) => {
  console.error(e.message || e);
  process.exit(1);
});
