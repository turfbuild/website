// Pages

let VERSION = '';
const banner = () => `<!-- generated by scripts/generate-reference.mjs from turf-mcp-server ${VERSION}; do not edit -->`;
const note = (what) =>
  `:::note[Generated]\n${what} Generated from turf-mcp-server ${VERSION} by \`scripts/generate-reference.mjs\`: change the server, then run \`npm run generate\`.\n:::`;

function page({ title, description, order, label }, body) {
  const fm = ['---', `title: ${yamlString(title)}`, `description: ${yamlString(description)}`];
  if (order !== undefined || label) {
    fm.push('sidebar:');
    if (label) fm.push(`  label: ${yamlString(label)}`);
    if (order !== undefined) fm.push(`  order: ${order}`);
  }
  fm.push('---');
  return `${fm.join('\n')}\n${banner()}\n\n${body.trim()}\n`;
}

function write(rel, content) {
  const file = path.join(REF, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  written.push(rel);
}
const written = [];

function tierLine(tiers) {
  return `**[Tiers](${DOCS_BASE}/server/#tiers):** ${tiers.join(' · ')}`;
}

function toolOrder(name, all) {
  for (let g = 0; g < TOOL_GROUPS.length; g++) {
    const i = TOOL_GROUPS[g][1].indexOf(name);
    if (i >= 0) return (g + 1) * 100 + i + 1;
  }
  const extra = all.filter((n) => !TOOL_GROUPS.some(([, ns]) => ns.includes(n))).sort();
  return 900 + extra.indexOf(name) + 1;
}

function toolPage(tool, tiers, allNames) {
  const desc = tool.description || '';
  const ann = { ...(tool.annotations || {}) };
  if (tool.title && !ann.title) ann.title = tool.title;
  const annRows = ANNOTATIONS.filter((k) => k in ann).map((k) => `| \`${k}\` | ${escapeText(String(ann[k]), { cell: true })} |`);
  const sections = [
    note(`The \`${tool.name}\` tool as the server lists it in \`tools/list\`.`),
    escapeText(desc),
    tierLine(tiers),
  ];
  if (annRows.length) sections.push(`## Annotations\n\n| Annotation | Value |\n|---|---|\n${annRows.join('\n')}`);
  sections.push(`## Arguments\n\n${argumentTable(tool.inputSchema)}`);
  if (tool.outputSchema) sections.push(`## Result\n\n${argumentTable(tool.outputSchema)}`);
  return page(
    { title: tool.name, description: trimTo(plain(firstSentence(desc))), order: toolOrder(tool.name, allNames) },
    sections.join('\n\n'),
  );
}

function promptsPage(prompts, promptTiers) {
  const body = [
    note('The prompts the server lists in `prompts/list`.'),
    `The server offers ${count(prompts.length, 'prompt')}. A client shows them as commands the user runs; in Claude Code they are [slash commands](${DOCS_BASE}/slash-commands/). Arguments are listed in the order the server declares them.`,
  ];
  for (const p of prompts) {
    const args = p.arguments || [];
    const table = args.length
      ? `| Argument | Required | Description |\n|---|---|---|\n${args
          .map((a) => `| \`${a.name}\` | ${a.required ? 'yes' : 'no'} | ${escapeText(a.description || '', { cell: true })} |`)
          .join('\n')}`
      : 'No arguments.';
    const title = p.title ? `${escapeText(p.title)}\n\n` : '';
    body.push(`## ${p.name}\n\n${title}${escapeText(p.description || '')}\n\n${tierLine(promptTiers[p.name])}\n\n${table}`);
  }
  return page(
    {
      title: 'Prompts',
      description: trimTo(
        `The ${count(prompts.length, 'prompt')} turf-mcp-server lists (${prompts.map((p) => p.name).join(', ')}), with their arguments in the order the server declares them and the tiers that list each.`,
      ),
    },
    body.join('\n\n'),
  );
}

function resourcesPage(resources, templates, resTiers) {
  const entry = (r, uri) =>
    `### ${escapeText(r.name || uri)}\n\n\`${uri}\`\n\n${escapeText(r.description || '')}\n\n` +
    `| MIME type | Tiers |\n|---|---|\n| ${r.mimeType ? `\`${r.mimeType}\`` : '—'} | ${resTiers[uri].join(' · ')} |`;
  const body = [
    note('The resources the server lists in `resources/list` and `resources/templates/list`.'),
    `The server lists ${count(resources.length, 'resource')} and ${count(templates.length, 'resource template')}. A template's \`{name}\` parts are filled in to read one; \`{?name}\` is an optional query parameter.`,
    `## Resources\n\n${resources.map((r) => entry(r, r.uri)).join('\n\n') || 'None.'}`,
    `## Resource templates\n\n${templates.map((t) => entry(t, t.uriTemplate)).join('\n\n') || 'None.'}`,
  ];
  return page(
    {
      title: 'Resources',
      description: trimTo(
        `The turf:// resources and resource templates turf-mcp-server lists: workspaces, a workspace, its state, a convergence and a round's plan, as JSON.`,
      ),
    },
    body.join('\n\n'),
  );
}

const SKILL_ORDER = { deployment: 100, authoring: 200, guide: 300 };
const cap = (s) => s[0].toUpperCase() + s.slice(1);
const WORDS = ['no', 'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine'];
const count = (n, noun) => `${WORDS[n] ?? n} ${noun}${n === 1 ? '' : 's'}`;

const knownIn = (skills) => (skill, name) => typeof skills[skill]?.files[name] === 'string';

function skillPages(skills) {
  const known = knownIn(skills);
  for (const s of SKILLS) {
    const { heading, body } = splitTitle(skills[s].body);
    const desc = fitSentences(plain(firstParagraph(body)));
    write(
      `skills/${s}.md`,
      page(
        { title: `${cap(s)} skill`, description: desc, order: SKILL_ORDER[s] },
        `${note(`The text the \`skill_${s}\` tool returns${heading ? `, headed “${escapeText(heading)}”` : ''}.`)}\n\n${renderSkillText(body, s, known)}`,
      ),
    );
    const names = Object.keys(skills[s].files).sort();
    names.forEach((name, i) => {
      const text = skills[s].files[name];
      const { heading: h, body: b } = splitTitle(text);
      write(
        `skills/${s}/${name}.md`,
        page(
          { title: h || name, description: fitSentences(plain(firstParagraph(b))), order: SKILL_ORDER[s] + i + 1 },
          `${note(`The file \`references/${name}.md\` of the ${s} skill, as \`read_skill_file({ skill_name: "${s}", path: "references/${name}.md" })\` returns it.`)}\n\n${renderSkillText(b, s, known)}`,
        ),
      );
    });
  }
}

function instructionsPage(byTier, known) {
  const full = byTier.full.instructions;
  const others = TIERS.filter((t) => t !== 'full' && byTier[t].instructions !== full);
  const body = [
    note('The `instructions` string of the server’s `initialize` result.'),
    `This is the text turf-mcp-server hands every agent in its \`initialize\` result, before the first tool call. It carries the loop, the approval rule and the safety rules, so an agent that has loaded nothing else still knows them. The procedure lives in the skills: the text sends the agent to the [deployment skill](${skillUrl('deployment')}) first.`,
    `The text at the full tier, verbatim (its headings one level down):\n\n${renderSkillText(full, 'deployment', known)}`,
  ];
  if (others.length) {
    // The other tiers append one section to the full tier's text. When each appends a section under the
    // same heading, the heading is said once and each tier's paragraph follows; otherwise each tier's
    // text is shown whole.
    const added = others.map((t) => {
      const text = byTier[t].instructions;
      return { tier: t, text: text.startsWith(full) ? text.slice(full.length).trim() : null, whole: text };
    });
    const heads = added.map((a) => a.text && a.text.match(/^#{1,6} (.+)\n\n([\s\S]+)$/));
    const same = heads.every((h) => h && h[1] === heads[0][1]);
    const tiers = others.join(', ').replace(/, ([^,]+)$/, ' and $1');
    if (same) {
      body.push(
        `## At the other tiers\n\nAt the ${tiers} tiers the server appends a section headed “${escapeText(heads[0][1])}”. Its text at each tier, verbatim:`,
      );
      added.forEach((a, i) => body.push(`### ${a.tier}\n\n${renderSkillText(heads[i][2].trim(), 'deployment', known)}`));
    } else {
      body.push(`## At the other tiers\n\nThe text differs at the ${tiers} tiers. Each tier's text, verbatim:`);
      for (const a of added) {
        body.push(`### ${a.tier}\n\n${renderSkillText(a.text ?? a.whole, 'deployment', known).replace(/^(#{1,4}) /gm, '##$1 ')}`);
      }
    }
  }
  return page(
    {
      title: 'Server instructions',
      description: trimTo(
        'The instructions turf-mcp-server hands every agent at connection, verbatim: the loop, the approval rule, the safety rules and the model, with what each tier adds.',
      ),
    },
    body.join('\n\n'),
  );
}

