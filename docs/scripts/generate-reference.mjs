#!/usr/bin/env node
// Generates the MCP reference from a turf-mcp-server binary: the tool pages, the prompts and
// resources pages, the skills and their reference files, and the server instructions.
//
//   TURF_MCP_SERVER=/path/to/turf-mcp-server npm run generate
//
// The server is started over stdio once per tier (read, plan, apply, full) so each tool page can say
// which tiers list it. Nothing here needs the Turf engine: tools/list, prompts/list, resources/list,
// resources/templates/list, the three skill tools and read_skill_file are answered by the server alone.
// The output is committed; the docs build never runs this. Re-run it once per release: the diff is the
// release's reference change. The output depends only on what the server returns (no timestamps), so a
// second run against the same binary changes nothing.

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const REF = path.resolve(here, '../src/content/docs/reference');
const BIN = process.env.TURF_MCP_SERVER || 'turf-mcp-server';
const TIERS = ['read', 'plan', 'apply', 'full'];
const SKILLS = ['deployment', 'authoring', 'guide'];
const DOCS_BASE = '/docs/reference';

// The sidebar order of the tool pages: Starlight sorts an autogenerated group by sidebar.order, so the
// groups below read in this order without a directory each.
const TOOL_GROUPS = [
  ['Configuration', ['init']],
  ['Workspaces', ['open', 'close', 'status', 'list', 'delete']],
  ['Convergence', ['up', 'destroy', 'refresh', 'import', 'invoke', 'plan', 'apply', 'cancel']],
  ['State', ['show', 'output', 'state_list', 'taint', 'untaint']],
  ['Providers', ['provider_search', 'provider_describe']],
  ['Skills', ['skill_deployment', 'skill_authoring', 'skill_guide', 'read_skill_file']],
];
const ANNOTATIONS = ['title', 'readOnlyHint', 'destructiveHint', 'idempotentHint', 'openWorldHint'];

// ---------------------------------------------------------------------------------------------
// The server

function serverVersion() {
  const out = execFileSync(BIN, ['--version'], { encoding: 'utf8' });
  return out.split('\n')[0].trim();
}

async function connect(tier) {
  const transport = new StdioClientTransport({
    command: BIN,
    args: ['--tier', tier],
    env: { ...process.env },
    stderr: 'pipe',
  });
  let stderr = '';
  transport.stderr?.on('data', (d) => {
    stderr += d;
  });
  const client = new Client({ name: 'turf-docs-generate-reference', version: '1.0.0' });
  try {
    await client.connect(transport);
  } catch (e) {
    throw new Error(`could not start ${BIN} --tier ${tier}: ${e.message}\n${stderr}`);
  }
  return { client, stderr: () => stderr };
}

async function listAll(fn, key) {
  const items = [];
  let cursor;
  do {
    const page = await fn(cursor ? { cursor } : undefined);
    items.push(...(page[key] || []));
    cursor = page.nextCursor;
  } while (cursor);
  return items;
}

async function readTier(tier) {
  const { client, stderr } = await connect(tier);
  try {
    const caps = client.getServerCapabilities() || {};
    const out = {
      tier,
      serverInfo: client.getServerVersion(),
      instructions: client.getInstructions() || '',
      tools: await listAll((p) => client.listTools(p), 'tools'),
      prompts: caps.prompts ? await listAll((p) => client.listPrompts(p), 'prompts') : [],
      resources: caps.resources ? await listAll((p) => client.listResources(p), 'resources') : [],
      templates: caps.resources
        ? await listAll((p) => client.listResourceTemplates(p), 'resourceTemplates')
        : [],
    };
    if (tier === 'full') out.skills = await readSkills(client);
    return out;
  } catch (e) {
    throw new Error(`${BIN} --tier ${tier}: ${e.message}\n${stderr()}`);
  } finally {
    await client.close();
  }
}

function textOf(result, what) {
  if (result.isError) {
    const msg = (result.content || []).map((c) => c.text || '').join('\n');
    throw new Error(`${what} failed: ${msg}`);
  }
  const text = (result.content || []).filter((c) => c.type === 'text').map((c) => c.text).join('\n');
  if (!text) throw new Error(`${what} returned no text`);
  return text;
}

// Each skill's SKILL.md, then every references/<name>.md it names, and every one those name in turn.
// A reference written `skill_<other> → references/<name>.md` belongs to the other skill.
async function readSkills(client) {
  const skills = {};
  for (const s of SKILLS) {
    skills[s] = { body: textOf(await client.callTool({ name: `skill_${s}`, arguments: {} }), `skill_${s}`), files: {} };
  }
  const queue = [];
  const want = (skill, name) => {
    if (!skills[skill] || name in skills[skill].files) return;
    skills[skill].files[name] = null;
    queue.push([skill, name]);
  };
  for (const s of SKILLS) for (const r of referencesIn(skills[s].body, s)) want(r.skill, r.name);
  while (queue.length) {
    const [skill, name] = queue.shift();
    const res = await client.callTool({
      name: 'read_skill_file',
      arguments: { skill_name: skill, path: `references/${name}.md` },
    });
    const text = textOf(res, `read_skill_file(${skill}, references/${name}.md)`);
    skills[skill].files[name] = text;
    for (const r of referencesIn(text, skill)) want(r.skill, r.name);
  }
  return skills;
}

// ---------------------------------------------------------------------------------------------
// Markdown handling: fences, code spans, escaping

// Splits markdown into fenced blocks (left alone) and prose runs. Fences open with ``` or ~~~ at any
// indentation (skill text nests them in list items) and close with the same character, at least as long.
function splitFences(md) {
  const lines = md.split('\n');
  const parts = [];
  let buf = [];
  let fence = null;
  const flush = (kind) => {
    if (buf.length) parts.push({ kind, text: buf.join('\n') });
    buf = [];
  };
  for (const line of lines) {
    const m = line.match(/^\s*(`{3,}|~{3,})/);
    if (!fence && m) {
      flush('prose');
      fence = m[1];
      buf.push(line);
    } else if (fence && m && m[1][0] === fence[0] && m[1].length >= fence.length && line.trim() === m[1]) {
      buf.push(line);
      flush('fence');
      fence = null;
    } else {
      buf.push(line);
    }
  }
  flush(fence ? 'fence' : 'prose');
  return parts;
}

// Splits a prose run into code spans and text. A code span opens with a run of N backticks and closes
// at the next run of exactly N; it may cross lines. An unmatched run is literal text.
function splitCode(text) {
  const parts = [];
  let i = 0;
  let last = 0;
  while (i < text.length) {
    if (text[i] !== '`') {
      i++;
      continue;
    }
    let j = i;
    while (text[j] === '`') j++;
    const run = text.slice(i, j);
    let k = j;
    let close = -1;
    while (k < text.length) {
      const n = text.indexOf(run, k);
      if (n < 0) break;
      let e = n + run.length;
      if (text[n - 1] !== '`' && text[e] !== '`') {
        close = n;
        break;
      }
      while (text[e] === '`') e++;
      k = e;
    }
    if (close < 0) {
      i = j;
      continue;
    }
    if (i > last) parts.push({ code: false, text: text.slice(last, i) });
    parts.push({ code: true, text: text.slice(i, close + run.length), inner: text.slice(j, close) });
    i = last = close + run.length;
  }
  if (last < text.length) parts.push({ code: false, text: text.slice(last) });
  return parts;
}

// Applies fn to the text outside fences and code spans.
function mapProse(md, fn) {
  return splitFences(md)
    .map((p) => (p.kind === 'fence' ? p.text : splitCode(p.text).map((c) => (c.code ? c.text : fn(c.text))).join('')))
    .join('\n');
}

// Prose the generator writes from schema and tool descriptions: plain sentences that use backticks
// for code and nothing else of markdown. `<` would open an HTML tag, `*` and a word-edge `_` emphasis
// ('__cty_sensitive__' would turn bold); inside a table cell `|` ends the cell.
function escapeText(s, { cell = false } = {}) {
  const out = mapProse(s, (t) =>
    t
      .replace(/\\/g, '\\\\')
      .replace(/</g, '&lt;')
      .replace(/\*/g, '\\*')
      .replace(/_/g, (m, off, str) => (/[A-Za-z0-9]/.test(str[off - 1] || '') && /[A-Za-z0-9]/.test(str[off + 1] || '') ? m : '\\_')),
  );
  return cell ? out.replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ') : out;
}

// Skill text is markdown already: only a bare `<name>` outside code is escaped, so it renders instead
// of being swallowed as an HTML tag.
function escapeSkillProse(t) {
  return t.replace(/<(?=[A-Za-z/!?])/g, '&lt;');
}

// Drops every heading one level when the text still holds an h1, so the page's title stays the only
// h1 (Starlight renders the title as one). Text whose first heading was taken for the title keeps its
// levels: its ## sections are the page's h2s.
function demoteHeadings(md) {
  const hasH1 = splitFences(md).some((p) => p.kind === 'prose' && /^# /m.test(p.text));
  if (!hasH1) return md;
  return splitFences(md)
    .map((p) => (p.kind === 'fence' ? p.text : p.text.replace(/^(#{1,5}) /gm, '#$1 ')))
    .join('\n');
}

function plain(md) {
  return md
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/`+([^`]*)`+/g, '$1')
    .replace(/\*\*([^*]*)\*\*/g, '$1')
    .replace(/(^|[^\w])[*_]([^*_]+)[*_](?=[^\w]|$)/g, '$1$2')
    .replace(/\s+/g, ' ')
    .trim();
}

function trimTo(s, n = 155) {
  if (s.length <= n) return s;
  const cut = s.slice(0, n - 1);
  const sp = cut.lastIndexOf(' ');
  return `${(sp > n * 0.6 ? cut.slice(0, sp) : cut).replace(/[\s,;:—–-]+$/, '')}…`;
}

// The first sentence: up to a . ! or ? followed by whitespace and a capital letter or a backtick,
// or by the end of the text. "e.g. 'aws'" and "i.e. the" never end one.
function firstSentence(s) {
  const m = s.match(/^[\s\S]*?[.!?](?=\s+[A-Z`*(]|\s*$)/);
  return (m ? m[0] : s).trim();
}

// As many whole sentences of a plain-text paragraph as fit in n characters; a first sentence longer
// than that is cut at a word with an ellipsis.
function fitSentences(text, n = 155) {
  const sentences = text.split(/(?<=[.!?])\s+(?=[A-Z"(])/);
  let out = '';
  for (const s of sentences) {
    const next = out ? `${out} ${s}` : s;
    if (next.length > n) break;
    out = next;
  }
  return out || trimTo(sentences[0], n);
}

function firstParagraph(md) {
  for (const p of splitFences(md)) {
    if (p.kind === 'fence') continue;
    for (const para of p.text.split(/\n\s*\n/)) {
      const t = para.trim();
      if (!t || /^#/.test(t) || /^[|>]/.test(t) || /^<!--/.test(t)) continue;
      return t;
    }
  }
  return '';
}

function yamlString(s) {
  return JSON.stringify(s);
}

