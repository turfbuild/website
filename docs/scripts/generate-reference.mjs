// Skill links

const skillFileUrl = (skill, name) => `${DOCS_BASE}/skills/${skill}/${name}/`;
const skillUrl = (skill) => `${DOCS_BASE}/skills/${skill}/`;

// A code span naming a reference file, in one of three spellings:
//   `references/plans.md`                          — the skill's own
//   `skill_deployment → references/plans.md`        — another skill's
//   `read_skill_file({ skill_name: "guide", path: "references/taco.md" })`
function matchReference(inner, skill) {
  let m = inner.match(/^references\/([\w-]+)\.md$/);
  if (m) return { skill, name: m[1] };
  m = inner.match(/^skill_(\w+)\s*→\s*references\/([\w-]+)\.md$/);
  if (m && SKILLS.includes(m[1])) return { skill: m[1], name: m[2] };
  m = inner.match(/^read_skill_file\(\{\s*skill_name:\s*"(\w+)",\s*path:\s*"references\/([\w-]+)\.md"\s*\}\)$/);
  if (m && SKILLS.includes(m[1])) return { skill: m[1], name: m[2] };
  return null;
}

function referencesIn(md, skill) {
  const refs = [];
  for (const p of splitFences(md)) {
    if (p.kind === 'fence') continue;
    for (const c of splitCode(p.text)) {
      if (!c.code) continue;
      const r = matchReference(c.inner, skill);
      if (r) refs.push(r);
    }
  }
  return refs;
}

// Rewrites skill text for a docs page: reference code spans become links to their pages, `skill_x`
// spans link to the skill's page, bare `<` is escaped, and headings drop one level.
function renderSkillText(md, skill, known) {
  const rewritten = splitFences(md)
    .map((p) => {
      if (p.kind === 'fence') return p.text;
      return splitCode(p.text)
        .map((c) => {
          if (!c.code) return escapeSkillProse(c.text);
          const r = matchReference(c.inner, skill);
          if (r && known(r.skill, r.name)) return `[${c.text}](${skillFileUrl(r.skill, r.name)})`;
          const s = c.inner.match(/^skill_(\w+)$/);
          if (s && SKILLS.includes(s[1])) return `[${c.text}](${skillUrl(s[1])})`;
          return c.text;
        })
        .join('');
    })
    .join('\n');
  return demoteHeadings(rewritten);
}

// Takes the first `# ` heading off a skill text: the page's title carries it.
function splitTitle(md) {
  const m = md.match(/^\s*# (.+)\n/);
  if (!m) return { heading: '', body: md };
  return { heading: m[1].trim(), body: md.slice(m[0].length).replace(/^\s*\n/, '') };
}

// ---------------------------------------------------------------------------------------------
// JSON Schema → argument table

function resolveRef(schema, root) {
  let s = schema;
  const seen = new Set();
  while (s && s.$ref && !seen.has(s.$ref)) {
    seen.add(s.$ref);
    const m = s.$ref.match(/^#\/(\$defs|definitions)\/(.+)$/);
    if (!m) break;
    const target = root[m[1]]?.[decodeURIComponent(m[2]).replace(/~1/g, '/').replace(/~0/g, '~')];
    if (!target) break;
    const { $ref, ...rest } = s;
    s = { ...target, ...rest };
  }
  return s || {};
}

function typeOf(schema, root) {
  const s = resolveRef(schema, root);
  const alts = s.anyOf || s.oneOf;
  if (alts) {
    const types = [...new Set(alts.map((a) => typeOf(a, root)).filter((t) => t !== 'null'))];
    return types.join(' or ') || 'null';
  }
  if ('const' in s) return `const ${JSON.stringify(s.const)}`;
  let types = Array.isArray(s.type) ? s.type : s.type ? [s.type] : [];
  if (types.length > 1) types = types.filter((t) => t !== 'null');
  if (!types.length) {
    if (s.properties) types = ['object'];
    else if (s.items) types = ['array'];
    else if (s.enum) types = [...new Set(s.enum.map((v) => (v === null ? 'null' : typeof v)))];
    else return 'any';
  }
  return types
    .map((t) => {
      if (t === 'array' && s.items) return `array of ${typeOf(s.items, root)}`;
      if (t === 'object' && !s.properties && s.additionalProperties && typeof s.additionalProperties === 'object')
        return `map of ${typeOf(s.additionalProperties, root)}`;
      return t;
    })
    .join(' or ');
}

function describe(schema) {
  const parts = [];
  if (schema.description) parts.push(schema.description.trim());
  if (schema.enum) parts.push(`One of: ${schema.enum.map((v) => `\`${JSON.stringify(v)}\``).join(', ')}.`);
  if ('default' in schema) parts.push(`Default: \`${JSON.stringify(schema.default)}\`.`);
  return parts.join(' ');
}

// One row per property; a nested object's properties follow it, named by their path:
// `action_results.<key>.succeeded`, `diagnostics[].severity`.
function schemaRows(schema, root, prefix = '', rows = [], depth = 0) {
  const s = resolveRef(schema, root);
  const props = s.properties || {};
  const required = new Set(s.required || []);
  for (const name of Object.keys(props)) {
    const p = resolveRef(props[name], root);
    const full = `${prefix}${name}`;
    rows.push({ name: full, type: typeOf(p, root), required: required.has(name), description: describe(p) });
    if (depth < 6) nested(p, root, full, rows, depth + 1);
  }
  return rows;
}

function nested(p, root, full, rows, depth) {
  const types = Array.isArray(p.type) ? p.type : [p.type];
  if (p.properties) schemaRows(p, root, `${full}.`, rows, depth);
  else if (types.includes('object') && p.additionalProperties && typeof p.additionalProperties === 'object') {
    const v = resolveRef(p.additionalProperties, root);
    if (v.properties) schemaRows(v, root, `${full}.<key>.`, rows, depth);
  }
  if (types.includes('array') && p.items) {
    const it = resolveRef(p.items, root);
    if (it.properties) schemaRows(it, root, `${full}[].`, rows, depth);
  }
}

function argumentTable(schema) {
  const rows = schemaRows(schema || {}, schema || {});
  if (!rows.length) return 'No arguments.\n';
  const head = '| Name | Type | Required | Description |\n|---|---|---|---|\n';
  return (
    head +
    rows
      .map(
        (r) =>
          `| \`${r.name}\` | ${escapeText(r.type, { cell: true })} | ${r.required ? 'yes' : 'no'} | ${escapeText(r.description, { cell: true })} |`,
      )
      .join('\n') +
    '\n'
  );
}

